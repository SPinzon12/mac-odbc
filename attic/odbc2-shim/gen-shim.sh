#!/bin/bash
# Generate the trampoline + pointer-table scaffolding for the ODBC 2.x shim,
# straight from the real driver's export list. Handwritten logic lives in
# odbc2full.c; everything mechanical is generated here.
#
#   trampolines.s : asm tail-jumps for every driver symbol NOT implemented in C
#   shim_ptrs.[ch]: pointer table for ALL driver symbols (the C wrappers and
#                   the ODBC 2.x layer call through these pointers, resolved
#                   explicitly against the driver handle — never the flat
#                   namespace, so there is no way to recurse into the DM)
set -euo pipefail

DRV=/Library/ODBC/psqlodbc.bundle/Contents/MacOS/psqlodbcw.so
ALL=$(mktemp); TRAMP=$(mktemp)

nm -gU "$DRV" | awk '{print $NF}' | sed 's/^_//' | grep '^SQL' | sort -u > "$ALL"

# Implemented in C in odbc2full.c (traced entry points + ODBC 2.x surface):
# no trampoline may duplicate them or the link fails with duplicate symbols.
grep -vxE 'SQLAllocHandle|SQLFreeHandle|SQLSetEnvAttr|SQLGetEnvAttr|SQLSetConnectAttr|SQLSetConnectAttrW|SQLGetConnectAttr|SQLGetConnectAttrW|SQLDriverConnect|SQLDriverConnectW|SQLConnect|SQLConnectW|SQLGetInfo|SQLGetInfoW|SQLGetDiagRec|SQLGetDiagRecW|SQLAllocEnv|SQLAllocConnect|SQLAllocStmt|SQLFreeEnv|SQLFreeConnect|SQLTransact|SQLError|SQLGetConnectOption|SQLSetConnectOption|SQLSetConnectOptionW|SQLGetStmtOption|SQLSetStmtOption|SQLParamOptions|SQLColAttributes|SQLColAttributesW' \
    "$ALL" > "$TRAMP"

echo "$(wc -l < "$ALL") símbolos en la tabla de punteros, $(wc -l < "$TRAMP") trampolinas"

{
    echo "/* generated by gen-shim.sh — do not edit */"
    echo ".text"
    while read -r s; do
        printf '.p2align 2\n.globl _%s\n_%s:\n\tadrp\tx16, _fp_%s@PAGE\n\tldr\tx16, [x16, _fp_%s@PAGEOFF]\n\tbr\tx16\n' \
            "$s" "$s" "$s" "$s"
    done < "$TRAMP"
} > trampolines.s

{
    echo "/* generated by gen-shim.sh — do not edit */"
    echo "#ifndef SHIM_PTRS_H"
    echo "#define SHIM_PTRS_H"
    while read -r s; do
        printf 'extern void *fp_%s;\n' "$s"
    done < "$ALL"
    echo "void shim_init(void *drv);"
    echo "#endif"
} > shim_ptrs.h

{
    echo "/* generated by gen-shim.sh — do not edit */"
    echo "#include <dlfcn.h>"
    echo '#include "shim_ptrs.h"'
    while read -r s; do
        printf '__attribute__((visibility("hidden"))) void *fp_%s;\n' "$s"
    done < "$ALL"
    echo "void shim_init(void *drv) {"
    while read -r s; do
        printf '\tfp_%s = dlsym(drv, "%s");\n' "$s" "$s"
    done < "$ALL"
    echo "}"
} > shim_ptrs.c

echo "generados: trampolines.s shim_ptrs.h shim_ptrs.c"
